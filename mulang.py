#!/usr/bin/env python3
"""
μLang 编译器
将 μLang 源码编译为 Python 代码并执行。
图灵完备，但绝对不好用。
"""

import sys
import re

class MuLangCompiler:
    def __init__(self, source: str):
        self.source = source
        self.lines = []
        self.labels = {}
        self.vars = set()
        self.py_lines = []
        
    def _error(self, msg: str, line_no: int):
        print(f"μLang Error [line {line_no}]: {msg}", file=sys.stderr)
        sys.exit(1)
        
    def _parse(self):
        """极简解析：按行分割，去注释，提取标签"""
        raw_lines = self.source.split('\n')
        for i, line in enumerate(raw_lines, 1):
            # 去注释
            if '#' in line:
                line = line[:line.index('#')]
            line = line.strip()
            if not line:
                continue
                
            # 提取标签 label:
            if ':' in line and not line.startswith(('SET', 'MOV', 'INC', 'DEC', 'ADD', 'SUB', 'JZ', 'JNZ', 'OUT')):
                parts = line.split(':', 1)
                label = parts[0].strip()
                self.labels[label] = len(self.lines)
                line = parts[1].strip()
                if not line:
                    continue
                    
            tokens = line.replace(',', ' ').split()
            self.lines.append((i, tokens))
            
    def _emit(self, code: str):
        self.py_lines.append("    " + code)
        
    def compile(self) -> str:
        self._parse()
        
        # 收集所有变量
        for line_no, tokens in self.lines:
            if not tokens:
                continue
            op = tokens[0].upper()
            if op in ('SET', 'INC', 'DEC', 'OUT') and len(tokens) >= 2:
                self.vars.add(tokens[1])
            elif op in ('MOV', 'ADD', 'SUB') and len(tokens) >= 3:
                self.vars.add(tokens[1])
                self.vars.add(tokens[2])
            elif op in ('JZ', 'JNZ') and len(tokens) >= 2:
                self.vars.add(tokens[1])
                
        # 生成 Python 代码
        self.py_lines.append("# Auto-generated by μLang Compiler")
        self.py_lines.append("def _mulang_run():")
        
        # 初始化所有变量为 0
        for v in sorted(self.vars):
            self._emit(f"{v} = 0")
            
        self._emit("pc = 0")
        self._emit("while True:")
        
        # 生成指令跳转表
        for idx, (line_no, tokens) in enumerate(self.lines):
            op = tokens[0].upper() if tokens else ''
            self._emit(f"    if pc == {idx}:")
            
            if op == 'SET':
                if len(tokens) != 3:
                    self._error("SET needs 2 args", line_no)
                self._emit(f"        {tokens[1]} = {tokens[2]}")
                self._emit(f"        pc += 1")
                
            elif op == 'MOV':
                if len(tokens) != 3:
                    self._error("MOV needs 2 args", line_no)
                self._emit(f"        {tokens[1]} = {tokens[2]}")
                self._emit(f"        pc += 1")
                
            elif op == 'INC':
                if len(tokens) != 2:
                    self._error("INC needs 1 arg", line_no)
                self._emit(f"        {tokens[1]} += 1")
                self._emit(f"        pc += 1")
                
            elif op == 'DEC':
                if len(tokens) != 2:
                    self._error("DEC needs 1 arg", line_no)
                self._emit(f"        {tokens[1]} = max(0, {tokens[1]} - 1)")
                self._emit(f"        pc += 1")
                
            elif op == 'ADD':
                if len(tokens) != 3:
                    self._error("ADD needs 2 args", line_no)
                self._emit(f"        {tokens[1]} += {tokens[2]}")
                self._emit(f"        pc += 1")
                
            elif op == 'SUB':
                if len(tokens) != 3:
                    self._error("SUB needs 2 args", line_no)
                self._emit(f"        {tokens[1]} = max(0, {tokens[1]} - {tokens[2]})")
                self._emit(f"        pc += 1")
                
            elif op == 'JZ':
                if len(tokens) != 3:
                    self._error("JZ needs 2 args", line_no)
                if tokens[2] not in self.labels:
                    self._error(f"Unknown label: {tokens[2]}", line_no)
                self._emit(f"        pc = {self.labels[tokens[2]]} if {tokens[1]} == 0 else pc + 1")
                
            elif op == 'JNZ':
                if len(tokens) != 3:
                    self._error("JNZ needs 2 args", line_no)
                if tokens[2] not in self.labels:
                    self._error(f"Unknown label: {tokens[2]}", line_no)
                self._emit(f"        pc = {self.labels[tokens[2]]} if {tokens[1]} != 0 else pc + 1")
                
            elif op == 'OUT':
                if len(tokens) != 2:
                    self._error("OUT needs 1 arg", line_no)
                self._emit(f"        print(chr({tokens[1]}), end='')")
                self._emit(f"        pc += 1")
                
            else:
                self._error(f"Unknown opcode: {op}", line_no)
                
        self._emit("    else:")
        self._emit("        break")
        self.py_lines.append("_mulang_run()")
        
        return '\n'.join(self.py_lines)
        
    def run(self):
        py_code = self.compile()
        print("=" * 50)
        print("Generated Python:")
        print("=" * 50)
        print(py_code)
        print("=" * 50)
        print("Output:")
        print("-" * 50)
        exec(py_code, {"__name__": "__main__"})


# ==================== 示例程序 ====================
# 这个程序输出 "HI"（证明它能做有用的事，虽然很难用）
demo_source = """
# 输出 ASCII 72 ('H') 和 73 ('I')
SET A 72
OUT A
INC A
OUT A
"""

if __name__ == "__main__":
    if len(sys.argv) > 1:
        with open(sys.argv[1], 'r') as f:
            MuLangCompiler(f.read()).run()
    else:
        print("Running demo program...")
        MuLangCompiler(demo_source).run()
